#[test]
fn refuses_when_git_cannot_read() {
    check_workspace(|root| {
        let (repository, _) = commit(&base());
        let shadow = shadow_git(concat!(
            "  every:*) echo 'fatal: stub git' >&2; exit 128 ;;\n",
            "  id:rev-parse) echo 'refs/heads/main'; exit 0 ;;\n",
            "  list:ls-tree) echo 'fatal: stub ls-tree' >&2; exit 128 ;;\n",
            "  record:ls-tree) printf 'a record with no tab\\0'; exit 0 ;;\n",
            "  blob:cat-file) echo 'fatal: stub cat-file' >&2; exit 128 ;;\n",
        ));
        let mut runs: Vec<(&str, Command)> = [
            ("git fails every call", "every"),
            ("git rev-parse prints no commit id", "id"),
            ("git ls-tree fails", "list"),
            (
                "git ls-tree prints a record the step cannot parse",
                "record",
            ),
            ("git cat-file fails", "blob"),
        ]
        .into_iter()
        .map(|(case, stub)| {
            let mut command = guard_command(root);
            command
                .current_dir(repository.path())
                .env("PATH", first_on_path(shadow.path()))
                .env("STUB_GIT_CASE", stub);
            (case, command)
        })
        .collect();

        let (outside_ascii, _) = commit(&with_base(&[file(
            &spelled("crates/", 0xe9, "/rust-toolchain.toml"),
            FOUR_KEYS,
        )]));
        let mut command = guard_command(root);
        command
            .current_dir(outside_ascii.path())
            .env("PATH", first_on_path(shadow.path()))
            .env("STUB_GIT_CASE", "blob");
        runs.push(("git cat-file fails on a path outside ASCII", command));

        let elsewhere = tempfile::tempdir().expect("a scratch directory is created");
        let ceiling = elsewhere
            .path()
            .canonicalize()
            .expect("the scratch directory resolves")
            .parent()
            .expect("the scratch directory has a parent")
            .to_path_buf();
        let mut command = guard_command(root);
        command
            .current_dir(elsewhere.path())
            .env("GIT_CEILING_DIRECTORIES", ceiling);
        runs.push(("a working directory that is no repository", command));

        let no_git = tempfile::tempdir().expect("a scratch directory is created");
        std::os::unix::fs::symlink(on_path("python3"), no_git.path().join("python3"))
            .expect("python3 is linked into the scratch PATH");
        let mut command = guard_command(root);
        command
            .current_dir(repository.path())
            .env("PATH", no_git.path());
        runs.push(("no git on PATH", command));

        for (case, output) in outputs_in_parallel(runs) {
            assert_cannot_read(&output, case);
            let says: &[&str] = match case {
                "git fails every call" => {
                    &["cannot read HEAD as a commit: git rev-parse exited 128: fatal: stub git"]
                }
                "git rev-parse prints no commit id" => &[
                    "cannot read HEAD as a commit: git rev-parse printed refs/heads/main, not a commit id",
                ],
                "git ls-tree fails" => &[
                    "cannot read the tree of ",
                    ": git ls-tree exited 128: fatal: stub ls-tree",
                ],
                "git ls-tree prints a record the step cannot parse" => &[
                    "cannot read the tree of ",
                    ": git ls-tree printed a record this step cannot parse: a record with no tab",
                ],
                "git cat-file fails" => &[
                    "cannot read rust-toolchain.toml (blob ",
                    ": git cat-file exited 128: fatal: stub cat-file",
                ],
                "git cat-file fails on a path outside ASCII" => &[
                    "cannot read crates/\\xe9/rust-toolchain.toml (blob ",
                    ": git cat-file exited 128: fatal: stub cat-file",
                ],
                "a working directory that is no repository" => &[
                    "cannot read HEAD as a commit: git rev-parse exited 128: fatal: not a git repository",
                ],
                _ => &["cannot read HEAD as a commit: git cannot run: "],
            };
            let said = said(&output);
            for fragment in says {
                assert!(
                    said.contains(fragment),
                    "{case}: the step must say what it could not read and why, `{fragment}`; it said:\n{said}"
                );
            }
        }
    });
}

#[test]
fn refuses_an_argument_that_names_no_commit() {
    check_workspace(|root| {
        let (repository, _) = commit(&base());
        let blob = git_ok(repository.path(), &["rev-parse", "HEAD:Cargo.toml"]);
        let tree = git_ok(repository.path(), &["rev-parse", "HEAD^{tree}"]);
        for argument in ["no-such-ref", blob.as_str(), tree.as_str(), "-h", "--all"] {
            let output = run(root, repository.path(), &[argument]);
            assert_cannot_read(&output, argument);
        }

        let output = run(root, repository.path(), &["HEAD", "HEAD"]);
        let said = said(&output);
        assert_eq!(
            output.status.code(),
            Some(2),
            "two arguments must exit 2; the step said:\n{said}"
        );
        assert!(
            said.contains("usage: build-input-guard [COMMIT]") && !claims_clean(&said),
            "two arguments must print the usage line and never clean; the step said:\n{said}"
        );
    });
}

#[test]
