#[derive(Clone)]
struct Plant {
    path: String,
    mode: &'static str,
    content: Vec<u8>,
}

fn bytes(path: &str, content: Vec<u8>) -> Plant {
    Plant {
        path: path.to_string(),
        mode: "100644",
        content,
    }
}

fn file(path: &str, content: &str) -> Plant {
    bytes(path, content.as_bytes().to_vec())
}

fn executable(path: &str, content: &str) -> Plant {
    Plant {
        mode: "100755",
        ..file(path, content)
    }
}

fn symlink(path: &str, target: &str) -> Plant {
    Plant {
        mode: "120000",
        ..file(path, target)
    }
}

fn gitlink(path: &str) -> Plant {
    Plant {
        mode: "160000",
        ..file(path, "1111111111111111111111111111111111111111")
    }
}

