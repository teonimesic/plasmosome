#[test]
fn a_symlink_leaving_the_repository_is_refused() {
    check_workspace(|root| {
        let outputs = refusals(
            root,
            vec![
                (
                    "a build script outside",
                    vec![symlink("crates/a/build.rs", "/opt/x.rs")],
                    vec![("crates/a/build.rs", "(symlink)")],
                ),
                (
                    "a source directory outside",
                    vec![symlink("crates/a/src", "../../../x")],
                    vec![("crates/a/src", "(symlink)")],
                ),
                (
                    "a chain",
                    vec![symlink("p", "q"), symlink("q", "../..")],
                    vec![("p", "(symlink)"), ("q", "(symlink)")],
                ),
                (
                    "a target that checkout cuts short at a NUL byte",
                    vec![symlink("z", "crates/a\0/../../..")],
                    vec![("z", "(symlink)")],
                ),
                (
                    "a target longer than any path",
                    vec![symlink("long", &"x/".repeat(3_000))],
                    vec![("long", "(symlink)")],
                ),
                (
                    "a target one byte over the bound",
                    vec![symlink("over", &format!("{}x", "x/".repeat(2_048)))],
                    vec![("over", "(symlink)")],
                ),
                (
                    "a skill symlink that leaves",
                    vec![symlink(".claude/skills/evil", "../../../outside")],
                    vec![(".claude/skills/evil", "(symlink)")],
                ),
                (
                    "a source directory that steps back out of .git",
                    vec![symlink("crates/a/src", "../../.git/../../outside")],
                    vec![("crates/a/src", "(symlink)")],
                ),
                (
                    "a build script that steps back out of .git",
                    vec![symlink("crates/a/build.rs", "../../.git/../../b.rs")],
                    vec![("crates/a/build.rs", "(symlink)")],
                ),
                (
                    "a name between the untracked name and the ..",
                    vec![symlink(
                        "crates/a/tests",
                        "../../.git/hooks/../../../outside",
                    )],
                    vec![("crates/a/tests", "(symlink)")],
                ),
                (
                    "a build's output directory and back",
                    vec![symlink("crates/a/benches", "../../target/../../outside")],
                    vec![("crates/a/benches", "(symlink)")],
                ),
                (
                    "a file and back",
                    vec![symlink(
                        "crates/a/examples",
                        "src/lib.rs/../../../../outside",
                    )],
                    vec![("crates/a/examples", "(symlink)")],
                ),
            ],
        );
        assert_says(
            &outputs,
            "a source directory that steps back out of .git",
            &[
                "crates/a/src: (symlink): a symlink to ../../.git/../../outside; it steps back with .. out of a name this commit does not track as a directory",
            ],
        );
        assert_says(
            &outputs,
            "a build script outside",
            &[
                "crates/a/build.rs: (symlink): a symlink to /opt/x.rs; it leads outside the repository",
            ],
        );
        assert_says(
            &outputs,
            "a chain",
            &[
                "p: (symlink): a symlink to q; it leads outside the repository",
                "q: (symlink): a symlink to ../..; it leads outside the repository",
            ],
        );
        assert_says(
            &outputs,
            "a target that checkout cuts short at a NUL byte",
            &[
                "z: (symlink): a symlink to crates/a\\x00/../../..; this step cannot read its target as a path",
            ],
        );
        assert_says(
            &outputs,
            "a target longer than any path",
            &[
                "long: (symlink): a symlink to a target longer than 4096 bytes; this step cannot read its target as a path",
            ],
        );
        assert_says(
            &outputs,
            "a target one byte over the bound",
            &[
                "over: (symlink): a symlink to a target longer than 4096 bytes; this step cannot read its target as a path",
            ],
        );
        assert_passes(root, &[symlink("docs/at-the-bound", &"x/".repeat(2_048))]);

        let loops = [
            (
                "a loop",
                vec![symlink("l1", "l2"), symlink("l2", "l1")],
                vec![("l1", "(symlink)"), ("l2", "(symlink)")],
            ),
            (
                "a self loop",
                vec![symlink("s", "s")],
                vec![("s", "(symlink)")],
            ),
            (
                "a loop that grows",
                vec![symlink("g", "g/g")],
                vec![("g", "(symlink)")],
            ),
        ];
        let fixtures: Vec<Vec<Plant>> = loops
            .iter()
            .map(|(_, plants, _)| with_base(plants))
            .collect();
        let (repository, shas) = commits(&fixtures);
        std::thread::scope(|scope| {
            let runs: Vec<_> = loops
                .iter()
                .zip(&shas)
                .map(|((route, _, expected), sha)| {
                    let repository = repository.path();
                    scope.spawn(move || {
                        let mut command = guard_command(root);
                        command.current_dir(repository).arg(sha);
                        let output = output_within(&mut command, route);
                        assert_refusal(&output, expected);
                        assert!(
                            said(&output).contains("it goes through more than 40 symlinks"),
                            "{route}: a loop must be refused as one; the step said:\n{}",
                            said(&output)
                        );
                    })
                })
                .collect();
            for run in runs {
                run.join().expect("every loop route is judged");
            }
        });
    });
}

#[test]
fn other_manifest_paths_stay_inside() {
    check_workspace(|root| {
        let workspace = |rest: &str| {
            file(
                "Cargo.toml",
                &format!("[workspace]\nresolver = \"2\"\n{rest}"),
            )
        };
        let in_package = |rest: &str| package("crates/a/Cargo.toml", "a", rest);
        let target = |table: &str| {
            member(
                "",
                &format!("\n[[{table}]]\nname = \"t\"\npath = \"../../../t.rs\"\n"),
            )
        };
        let at = |key: &'static str| vec![("crates/a/Cargo.toml", key)];
        let routes: Vec<Route> = vec![
            (
                "package.build",
                vec![in_package("build = \"../../../b.rs\"\n")],
                at("package.build"),
            ),
            (
                "package.build as an array",
                vec![in_package("build = [\"build.rs\", \"../../../b.rs\"]\n")],
                at("package.build[1]"),
            ),
            (
                "package.workspace",
                vec![in_package("workspace = \"../../..\"\n")],
                at("package.workspace"),
            ),
            (
                "workspace.members",
                vec![workspace("members = [\"crates/a\", \"../x/*\"]\n")],
                vec![("Cargo.toml", "workspace.members[1]")],
            ),
            (
                "workspace.default-members",
                vec![workspace(
                    "members = [\"crates/a\", \"crates/b\"]\ndefault-members = [\"../y\"]\n",
                )],
                vec![("Cargo.toml", "workspace.default-members[0]")],
            ),
            (
                "a member with no glob that nothing is tracked at",
                vec![workspace("members = [\"crates/a\", \"crates/c\"]\n")],
                vec![("Cargo.toml", "workspace.members[1]")],
            ),
            (
                "a .. after a glob",
                vec![workspace("members = [\"crates/*/../../../x\"]\n")],
                vec![("Cargo.toml", "workspace.members[0]")],
            ),
            (
                "[lib] path",
                vec![member("", "\n[lib]\npath = \"/opt/lib.rs\"\n")],
                at("lib.path"),
            ),
            (
                "[[bin]] path",
                vec![member(
                    "",
                    "\n[[bin]]\nname = \"ok\"\npath = \"src/main.rs\"\n\n[[bin]]\nname = \"m\"\npath = \"../../../m.rs\"\n",
                )],
                at("bin[1].path"),
            ),
            ("[[test]] path", vec![target("test")], at("test[0].path")),
            ("[[bench]] path", vec![target("bench")], at("bench[0].path")),
            (
                "[[example]] path",
                vec![target("example")],
                at("example[0].path"),
            ),
            (
                "[lib] path through a symlink that steps back out of .git",
                vec![
                    member("", "\n[lib]\npath = \"lnk/lib.rs\"\n"),
                    symlink("crates/a/lnk", "../../.git/../../x"),
                ],
                vec![
                    ("crates/a/Cargo.toml", "lib.path"),
                    ("crates/a/lnk", "(symlink)"),
                ],
            ),
            (
                "a member glob through a symlink that steps back out of .git",
                vec![
                    workspace("members = [\"lnk/*\"]\n"),
                    symlink("lnk", ".git/../crates"),
                ],
                vec![("Cargo.toml", "workspace.members[0]"), ("lnk", "(symlink)")],
            ),
        ];
        let outputs = refusals(root, routes);
        assert_says(
            &outputs,
            "[lib] path through a symlink that steps back out of .git",
            &[
                "crates/a/Cargo.toml: lib.path: \"lnk/lib.rs\" steps back with .. out of a name this commit does not track as a directory",
            ],
        );
        assert_says(
            &outputs,
            "package.build",
            &["crates/a/Cargo.toml: package.build: \"../../../b.rs\" leaves the repository"],
        );
        assert_says(
            &outputs,
            "a member with no glob that nothing is tracked at",
            &[
                "Cargo.toml: workspace.members[1]: \"crates/c\" does not resolve to a tracked directory: nothing is tracked there",
            ],
        );
        assert_says(
            &outputs,
            "a .. after a glob",
            &[
                "Cargo.toml: workspace.members[0]: \"crates/*/../../../x\" has a .. after a glob, which can leave the repository",
            ],
        );

        assert_passes(
            root,
            &[
                workspace("members = [\"crates/*\"]\ndefault-members = [\"crates/a\"]\n"),
                in_package(
                    "build = \"build.rs\"\n\n[lib]\npath = \"src/lib.rs\"\n\n[dependencies]\nb = { path = \"../b\" }\n",
                ),
                package("crates/b/Cargo.toml", "b", "build = false\n"),
            ],
        );
    });
}

