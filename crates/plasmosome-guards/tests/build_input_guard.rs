fn spelled(prefix: &str, code_point: u32, suffix: &str) -> String {
    let character = char::from_u32(code_point).expect("the code point is a character");
    format!("{prefix}{character}{suffix}")
}

fn printed(prefix: &str, code_point: u32, suffix: &str) -> String {
    let backslash = char::from(0x5c);
    format!("{prefix}{backslash}u{code_point:04x}{suffix}")
}

fn with_base(plants: &[Plant]) -> Vec<Plant> {
    base().into_iter().chain(plants.iter().cloned()).collect()
}

fn detached_from_any_inherited_repository(command: &mut Command) -> &mut Command {
    command
        .env("GIT_CONFIG_GLOBAL", "/dev/null")
        .env("GIT_CONFIG_SYSTEM", "/dev/null")
        .env_remove("GIT_DIR")
        .env_remove("GIT_WORK_TREE")
        .env_remove("GIT_INDEX_FILE")
        .env_remove("GIT_OBJECT_DIRECTORY")
        .env_remove("GIT_COMMON_DIR")
}

fn git_command(directory: &Path) -> Command {
    let mut command = Command::new("git");
    detached_from_any_inherited_repository(&mut command)
        .current_dir(directory)
        .env("GIT_AUTHOR_NAME", "A Person")
        .env("GIT_AUTHOR_EMAIL", "person@example.com")
        .env("GIT_COMMITTER_NAME", "A Person")
        .env("GIT_COMMITTER_EMAIL", "person@example.com");
    command
}

fn git_ok(directory: &Path, arguments: &[&str]) -> String {
    let output = git_command(directory)
        .args(arguments)
        .output()
        .expect("git runs");
    assert!(
        output.status.success(),
        "`git {}` failed in {}: {}",
        arguments.join(" "),
        directory.display(),
        String::from_utf8_lossy(&output.stderr)
    );
    String::from_utf8_lossy(&output.stdout).trim().to_string()
}

fn append_commit(stream: &mut Vec<u8>, reference: &str, plants: &[Plant]) {
    let message = b"fixture";
    stream.extend_from_slice(
        format!(
            "commit {reference}\ncommitter A Person <person@example.com> 1700000000 +0000\ndata {}\n",
            message.len()
        )
        .as_bytes(),
    );
    stream.extend_from_slice(message);
    stream.push(b'\n');
    for plant in plants {
        if plant.mode == "160000" {
            stream.extend_from_slice(
                format!(
                    "M 160000 {} {}\n",
                    String::from_utf8_lossy(&plant.content),
                    plant.path
                )
                .as_bytes(),
            );
        } else {
            stream.extend_from_slice(
                format!(
                    "M {} inline {}\ndata {}\n",
                    plant.mode,
                    plant.path,
                    plant.content.len()
                )
                .as_bytes(),
            );
            stream.extend_from_slice(&plant.content);
            stream.push(b'\n');
        }
    }
}

fn commits(fixtures: &[Vec<Plant>]) -> (TempDir, Vec<String>) {
    let repository = tempfile::tempdir().expect("a scratch directory is created");
    git_ok(repository.path(), &["init", "--quiet", "-b", "main"]);
    let references: Vec<String> = (0..fixtures.len())
        .map(|index| match index {
            0 => "refs/heads/main".to_string(),
            _ => format!("refs/heads/fixture-{index}"),
        })
        .collect();
    let mut stream = Vec::new();
    for (reference, plants) in references.iter().zip(fixtures) {
        append_commit(&mut stream, reference, plants);
    }
    let mut child = git_command(repository.path())
        .args(["fast-import", "--quiet"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .expect("git fast-import runs");
    child
        .stdin
        .take()
        .expect("git fast-import has a stdin pipe")
        .write_all(&stream)
        .expect("the fixture stream is written");
    let output = child.wait_with_output().expect("git fast-import finishes");
    assert!(
        output.status.success(),
        "the fixture commits were not created: {}",
        String::from_utf8_lossy(&output.stderr)
    );
    let mut arguments = vec!["rev-parse"];
    arguments.extend(references.iter().map(String::as_str));
    let shas: Vec<String> = git_ok(repository.path(), &arguments)
        .lines()
        .map(str::to_string)
        .collect();
    assert_eq!(
        shas.len(),
        fixtures.len(),
        "every fixture has its own commit"
    );
    (repository, shas)
}

fn commit(plants: &[Plant]) -> (TempDir, String) {
    let (repository, mut shas) = commits(&[plants.to_vec()]);
    (repository, shas.remove(0))
}

fn checked_out(plants: &[Plant]) -> (TempDir, String) {
    let (repository, sha) = commit(plants);
    git_ok(repository.path(), &["reset", "--hard", "--quiet"]);
    (repository, sha)
}

fn guard(root: &Path) -> PathBuf {
    root.join(".githooks").join("build-input-guard")
}

fn guard_command(root: &Path) -> Command {
    let script = guard(root);
    let mut command = match std::env::var_os("BUILD_INPUT_GUARD_RUNNER") {
        Some(runner) => {
            let mut command = Command::new(runner);
            command.arg(script);
            command
        }
        None => Command::new(script),
    };
    detached_from_any_inherited_repository(&mut command);
    command
}

fn run(root: &Path, directory: &Path, arguments: &[&str]) -> Output {
    guard_command(root)
        .current_dir(directory)
        .args(arguments)
        .output()
        .expect("the step runs")
}

fn said(output: &Output) -> String {
    format!(
        "{}{}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    )
}

fn claims_clean(said: &str) -> bool {
    said.lines()
        .any(|line| line.starts_with("build-input-guard: clean"))
}

fn assert_clean(output: &Output, sha: &str) {
    let said = said(output);
    assert_eq!(
        output.status.code(),
        Some(0),
        "the step refused a commit it should clear; it said:\n{said}"
    );
    let expected = format!("build-input-guard: clean ({sha})");
    assert!(
        String::from_utf8_lossy(&output.stdout)
            .lines()
            .any(|line| line == expected),
        "a clean verdict must name the commit it judged, `{expected}`; the step said:\n{said}"
    );
}

fn assert_refusal(output: &Output, expected: &[(&str, &str)]) {
    let said = said(output);
    assert_eq!(
        output.status.code(),
        Some(1),
        "expected a refusal, exit 1, naming {expected:?}; the step said:\n{said}"
    );
    for (path, key) in expected {
        let prefix = format!("build-input-guard: {path}: {key}: ");
        assert!(
            said.lines().any(|line| line.starts_with(&prefix)),
            "no line starts with `{prefix}`, so the refusal does not name that file and key; the step said:\n{said}"
        );
    }
    assert!(
        said.contains(HARM),
        "a refusal must state the harm from spec 026 word for word; the step said:\n{said}"
    );
    assert!(
        !said.contains("Traceback"),
        "a refusal must never be a crash; the step said:\n{said}"
    );
    assert!(
        !claims_clean(&said),
        "a refusal must not also claim clean; the step said:\n{said}"
    );
}

type Route<'a> = (&'a str, Vec<Plant>, Vec<(&'a str, &'a str)>);

fn refusals(root: &Path, routes: Vec<Route>) -> Vec<(String, String)> {
    let fixtures: Vec<Vec<Plant>> = routes
        .iter()
        .map(|(_, plants, _)| with_base(plants))
        .collect();
    let (repository, shas) = commits(&fixtures);
    let runs = routes
        .iter()
        .zip(&shas)
        .map(|((route, _, _), sha)| {
            let mut command = guard_command(root);
            command.current_dir(repository.path()).arg(sha);
            (*route, command)
        })
        .collect();
    let outputs = outputs_in_parallel(runs);
    routes
        .iter()
        .zip(outputs)
        .map(|((route, _, expected), (_, output))| {
            assert_eq!(
                output.status.code(),
                Some(1),
                "{route}: the step did not refuse it; it said:\n{}",
                said(&output)
            );
            assert_refusal(&output, expected);
            (route.to_string(), said(&output))
        })
        .collect()
}

fn said_for<'a>(outputs: &'a [(String, String)], route: &str) -> &'a str {
    outputs
        .iter()
        .find(|(name, _)| name == route)
        .map(|(_, said)| said.as_str())
        .unwrap_or_else(|| panic!("no route is named {route}"))
}

fn assert_passes(root: &Path, plants: &[Plant]) {
    let (repository, sha) = commit(&with_base(plants));
    let output = run(root, repository.path(), &[&sha]);
    assert_clean(&output, &sha);
}

fn assert_cannot_read(output: &Output, case: &str) {
    let said = said(output);
    assert_eq!(
        output.status.code(),
        Some(2),
        "{case}: a commit the step cannot read must exit 2, apart from a refusal; it said:\n{said}"
    );
    assert!(
        said.contains("build-input-guard: cannot read ")
            && said.contains("Refusing rather than passing"),
        "{case}: the step must say what it could not read and that it refuses; it said:\n{said}"
    );
    assert!(
        !claims_clean(&said),
        "{case}: a commit the step cannot read is never clean; it said:\n{said}"
    );
    assert!(
        !said.contains("Traceback"),
        "{case}: the step must never crash; it said:\n{said}"
    );
}

fn write_executable(path: &Path, content: &str) {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).expect("the parent directory is created");
    }
    std::fs::write(path, content).expect("the script is written");
    let mut permissions = std::fs::metadata(path)
        .expect("the script is readable")
        .permissions();
    permissions.set_mode(0o755);
    std::fs::set_permissions(path, permissions).expect("the script is made executable");
}

fn on_path(name: &str) -> PathBuf {
    std::env::var_os("PATH")
        .and_then(|path| {
            std::env::split_paths(&path)
                .map(|directory| directory.join(name))
                .find(|candidate| candidate.is_file())
        })
        .unwrap_or_else(|| panic!("{name} must be on PATH for this test"))
}

fn first_on_path(directory: &Path) -> String {
    format!(
        "{}:{}",
        directory.display(),
        std::env::var("PATH").unwrap_or_default()
    )
}

fn shadow_git(cases: &str) -> TempDir {
    let directory = tempfile::tempdir().expect("a scratch directory is created");
    let real = on_path("git");
    write_executable(
        &directory.path().join("git"),
        &format!(
            "#!/bin/sh\nfor command in \"$@\"; do\n  case $command in -*) ;; *) break ;; esac\ndone\ncase \"$STUB_GIT_CASE:$command\" in\n{cases}esac\nexec \"{}\" \"$@\"\n",
            real.display()
        ),
    );
    directory
}

fn outputs_in_parallel<'a>(mut runs: Vec<(&'a str, Command)>) -> Vec<(&'a str, Output)> {
    std::thread::scope(|scope| {
        let started: Vec<_> = runs
            .iter_mut()
            .map(|(case, command)| {
                let case: &'a str = case;
                (
                    case,
                    scope.spawn(move || command.output().expect("the step runs")),
                )
            })
            .collect();
        started
            .into_iter()
            .map(|(case, run)| (case, run.join().expect("the step's run finishes")))
            .collect()
    })
}

const STUBBED: [&str; 7] = [
    "cargo",
    "rustc",
    "rustup",
    "rustdoc",
    "rustfmt",
    "clippy-driver",
    "cargo-deny",
];

struct Stubs {
    scratch: TempDir,
}

impl Stubs {
    fn new() -> Self {
        let scratch = tempfile::tempdir().expect("a scratch directory is created");
        let stubs = Stubs { scratch };
        for name in STUBBED {
            for directory in ["bin", "cargo-home/bin", "home/.cargo/bin"] {
                write_executable(&stubs.at(directory).join(name), &stubs.script(name));
            }
        }
        for name in ["rustc", "cargo"] {
            write_executable(&stubs.at("tc/bin").join(name), &stubs.script(name));
        }
        write_executable(&stubs.at("log.sh"), &stubs.script("log.sh"));
        std::fs::create_dir_all(stubs.at("rustup-home")).expect("RUSTUP_HOME is created");
        stubs
    }

    fn at(&self, relative: &str) -> PathBuf {
        self.scratch.path().join(relative)
    }

    fn script(&self, name: &str) -> String {
        format!(
            "#!/bin/sh\nprintf '%s %s\\n' '{name}' \"$*\" >> '{}'\necho 'STUB {name} RAN' >&2\nexit 97\n",
            self.at("log").display()
        )
    }

    fn apply<'a>(&self, command: &'a mut Command) -> &'a mut Command {
        command
            .env("PATH", first_on_path(&self.at("bin")))
            .env("HOME", self.at("home"))
            .env("CARGO_HOME", self.at("cargo-home"))
            .env("RUSTUP_HOME", self.at("rustup-home"))
            .env("RUSTUP_TOOLCHAIN", self.at("tc"))
            .env("CARGO", self.at("bin/cargo"))
            .env("RUSTC", self.at("bin/rustc"))
            .env("RUSTDOC", self.at("bin/rustdoc"))
            .env("RUSTC_WRAPPER", self.at("bin/rustc"))
    }

    fn log(&self) -> String {
        std::fs::read_to_string(self.at("log")).unwrap_or_default()
    }
}

